package com.inventorymanagement.constants;

/**
 * Enumeration of security role names supported in the application.
 */
public enum RoleName {
    /**
     * Admin role with full system access.
     */
    ROLE_ADMIN,

    /**
     * Store manager role with catalog/inventory management access.
     */
    ROLE_STORE_MANAGER,

    /**
     * Sales executive role with sales operations access.
     */
    ROLE_SALES_EXECUTIVE
}
